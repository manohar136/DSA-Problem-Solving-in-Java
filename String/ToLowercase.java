// LeetCode 709 - To Lower Case
// Approach:
// 1. Take the given string.
// 2. Convert it into lowercase using toLowerCase().
// 3. Return the converted string.

// Time Complexity: O(n)
// Space Complexity: O(n)
class Solution {
    public String toLowerCase(String s) {
        
        // Create a new string after converting to lowercase
        String t = s.toLowerCase();
        
        // Return the result
        return t;
    }
}

